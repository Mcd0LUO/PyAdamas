# 442: `x: big = <常量整数表达式>` 的折叠必须**无条件**采用精确值。
# 只在「结果超 i64」时替换是不够的：子表达式可能已经在 int 域回绕
# （`(2**70) % 3` 的两个子式都超 i64，结果却是 1）。
# 另外 Python 的 // 和 % 是向下取整/与除数同号，C++ 是向零截断。


a: big = (2 ** 70) % 3
print(a)
b: big = (2 ** 70) >> 64
print(b)
c: big = (2 ** 70) // (2 ** 70)
print(c)
d: big = (2 ** 70) // -3
print(d)
e: big = (2 ** 70) % -3
print(e)
f: big = 2 ** 70 // (2 ** 69)
print(f)
g: big = -5
print(g)
h: big = 5
print(h)
i: big = 2 ** 70 + 1
print(i)
# --- expect ---
# 1
# 64
# 1
# -393530540239137101142
# -2
# 2
# -5
# 5
# 1180591620717411303425
