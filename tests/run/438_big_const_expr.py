# 438: `x: big = <全常量整数表达式>` 按精确值求值，不在 int 域里回绕。
# 默认 int 是 i64（docs/compatibility.md：溢出回绕），但目标是 big 时把回绕值
# 塞进去毫无意义 —— `2 ** 70` 曾经静默得 0。


a: big = 2 ** 70
print(a)
print(a + 1)
print(a * 2)

b: big = (1 << 100) - 1
print(b)
print(b // 3)
print(b % 7)

c: big = -(2 ** 80)
print(c)
print(c + 1)

d: big = 2 ** 126 - 1
print(d > 0)

e: big = 3 * 5 * 7 * 2 ** 60
print(e)

f: big = 2 ** 10
print(f)

g: int = 2 ** 10
print(g)
