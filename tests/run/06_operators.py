# 全部二元运算符与复合赋值，结果必须和 CPython 一致

def main() -> None:
    a = 10
    b = 3
    print(a + b, a - 4, a * 8 - 2, a // b, a % b, a // 3 + 1, a % 4, a // 4, a % 7, 15 // 7, 15 % 7)
    print(a + b, a - 4, a * 8 - 2, a // b, a % b, a // 3 + 1, a % 4, a // 4, a % 7, 15 // 7, 15 % 7)

    x = 10
    x += 3
    print(x, end=" ")
    x -= 10
    print(x, end=" ")
    x *= 8
    print(x, end=" ")
    x //= 6
    print(x, end=" ")
    x %= 7
    print(x, end=" ")
    x = 3
    x **= 2
    print(x, end=" ")
    x = 5
    x &= 3
    print(x, end=" ")
    x = 5
    x |= 2
    print(x, end=" ")
    x = 5
    x ^= 12
    print(x, end=" ")
    x = 1
    x <<= 2
    print(x, end=" ")
    x = 8
    x >>= 2
    print(x)

    print(3.5, -0.5, 6.0, 0.75, 1.0, 1.0, 8.0)
    print(f"7.5 // 2 = {7.5 // 2}")
    print(f"7.5 % 2 = {7.5 % 2}")
    print(f"-7.5 // 2 = {-7.5 // 2}")
    print(f"-7.5 % 2 = {-7.5 % 2}")
    print(f"2 ** 10 = {2 ** 10}")
    print(f"2.0 ** 0.5 = {2.0 ** 0.5}")

main()

# --- expect ---
# 13 6 78 3 1 4 2 2 3 2 1
# 13 6 78 3 1 4 2 2 3 2 1
# 13 3 24 4 4 9 1 7 9 4 2
# 3.5 -0.5 6.0 0.75 1.0 1.0 8.0
# 7.5 // 2 = 3.0
# 7.5 % 2 = 1.5
# -7.5 // 2 = -4.0
# -7.5 % 2 = 0.5
# 2 ** 10 = 1024
# 2.0 ** 0.5 = 1.4142135623730951
