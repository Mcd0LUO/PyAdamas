import math

def advance(b: list[float], dt: float, steps: int, nb: int) -> None:
    for _ in range(steps):
        for i in range(nb):
            for j in range(i + 1, nb):
                dx = b[i * 7] - b[j * 7]
                dy = b[i * 7 + 1] - b[j * 7 + 1]
                dz = b[i * 7 + 2] - b[j * 7 + 2]
                d2 = dx * dx + dy * dy + dz * dz
                mag = dt / (d2 * math.sqrt(d2))
                b[i * 7 + 3] -= dx * b[j * 7 + 6] * mag
                b[i * 7 + 4] -= dy * b[j * 7 + 6] * mag
                b[i * 7 + 5] -= dz * b[j * 7 + 6] * mag
                b[j * 7 + 3] += dx * b[i * 7 + 6] * mag
                b[j * 7 + 4] += dy * b[i * 7 + 6] * mag
                b[j * 7 + 5] += dz * b[i * 7 + 6] * mag
        for i in range(nb):
            b[i * 7] += dt * b[i * 7 + 3]
            b[i * 7 + 1] += dt * b[i * 7 + 4]
            b[i * 7 + 2] += dt * b[i * 7 + 5]

def energy(b: list[float], nb: int) -> float:
    e = 0.0
    for i in range(nb):
        e += 0.5 * b[i * 7 + 6] * (b[i * 7 + 3] * b[i * 7 + 3] +
                                   b[i * 7 + 4] * b[i * 7 + 4] +
                                   b[i * 7 + 5] * b[i * 7 + 5])
        for j in range(i + 1, nb):
            dx = b[i * 7] - b[j * 7]
            dy = b[i * 7 + 1] - b[j * 7 + 1]
            dz = b[i * 7 + 2] - b[j * 7 + 2]
            d = math.sqrt(dx * dx + dy * dy + dz * dz)
            e -= b[i * 7 + 6] * b[j * 7 + 6] / d
    return e

