# 456: 定宽整数的正 2 的幂除数（0.386 P0 收尾）。
# 定宽槽内的值一律非负（u64 是无符号域）→ // 与 % 各自退化成一条
# shrq / andq；以前走 idivq/divq，十几条指令加一次真除法。
# 用例取值都在宽度内、结果与 CPython 逐字节一致。

a: u8 = 200
b: u8 = 7
print(a // 2, a % 2, a // 8, a % 8, a // b, a % b)

c: i16 = 12345
print(c // 2, c % 2, c // 4, c % 4, c // 1024, c % 1024)
d: i16 = -12345
print(d // 2, d % 2, d // 4, d % 4)

e: u32 = 4000000000
print(e // 2, e % 2, e // 65536, e % 65536)

f: u64 = 18446744073709551615
print(f // 2, f % 2, f // 16, f % 16)

g: i64 = -9223372036854775807
print(g // 2, g % 2, g // 256, g % 256)
