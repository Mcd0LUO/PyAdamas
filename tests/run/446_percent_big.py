# 446: `%` 格式化支持 big（d/i/u/x/X/o 与 s/r）。
# 描述符里之前没有 big 档，落 `x` → "unsupported format argument type"。
# 现在用 B 档：整数转换交给 pa_big_fmt（与 format() 共用），
# s/r 用十进制串。


b: big = 1180591620717411303424
n: big = -1180591620717411303424
s: big = 5
print("%d" % b)
print("%x" % b)
print("%o" % b)
print("%10d|" % s)
print("%-10d|" % s)
print("%+d" % s)
print("%05d" % s)
print("%d" % n)
print("%5d|" % n)
print("%+d" % n)
print("%d%%" % b)
print("%s" % b)
print("%r" % b)
