# big 常量折叠综合：表达式折叠、精确语义、u64 字面量、超 __int128
# 0.382 合并自 4 个文件：438_big_const_expr.py, 442_big_const_fold_semantics.py, 443_big_const_u64_lit.py, 450_big_const_huge.py
# 每段包在独立函数里，避免同名变量/类跨段冲突。

# ── 原 438_big_const_expr.py ──
def _case_1() -> None:
    # 438: `x: big = <全常量整数表达式>` 按精确值求值，不在 int 域里回绕。
    # 默认 int 是 i64（docs/compatibility.md：溢出回绕），但目标是 big 时把回绕值
    # 塞进去毫无意义 —— `2 ** 70` 曾经静默得 0。


    a: big = 2 ** 70
    print(a)
    print(a + 1)
    print(a * 2)

    b: big = (1 << 100) - 1
    print(b)
    print(b // 3)
    print(b % 7)

    c: big = -(2 ** 80)
    print(c)
    print(c + 1)

    d: big = 2 ** 126 - 1
    print(d > 0)

    e: big = 3 * 5 * 7 * 2 ** 60
    print(e)

    f: big = 2 ** 10
    print(f)

    g: int = 2 ** 10
    print(g)

# ── 原 442_big_const_fold_semantics.py ──
def _case_2() -> None:
    # 442: `x: big = <常量整数表达式>` 的折叠必须**无条件**采用精确值。
    # 只在「结果超 i64」时替换是不够的：子表达式可能已经在 int 域回绕
    # （`(2**70) % 3` 的两个子式都超 i64，结果却是 1）。
    # 另外 Python 的 // 和 % 是向下取整/与除数同号，C++ 是向零截断。


    a: big = (2 ** 70) % 3
    print(a)
    b: big = (2 ** 70) >> 64
    print(b)
    c: big = (2 ** 70) // (2 ** 70)
    print(c)
    d: big = (2 ** 70) // -3
    print(d)
    e: big = (2 ** 70) % -3
    print(e)
    f: big = 2 ** 70 // (2 ** 69)
    print(f)
    g: big = -5
    print(g)
    h: big = 5
    print(h)
    i: big = 2 ** 70 + 1
    print(i)

# ── 原 443_big_const_u64_lit.py ──
def _case_3() -> None:
    # 443: u64 范围字面量（2^63..2^64-1）参与 big 常量折叠时必须按无符号读。
    # 以前 fold_int_const 只看 c->i（无符号位模式混在 int64 里），
    # `x: big = -9223372036854775808` 被算成 +2^63。


    a: big = -9223372036854775808
    print(a)
    b: big = 9223372036854775808 - 1
    print(b)
    c: big = 9223372036854775808 + 1
    print(c)
    d: big = -(9223372036854775808) + 1
    print(d)

# ── 原 450_big_const_huge.py ──
def _case_4() -> None:
    # 450: 超出 __int128 的常量表达式也要精确折叠（不能静默回绕成 0）。
    # 0.367 那版到 __int128 上限就放弃，回退到 int 域 → `2 ** 127` 得 0。
    # 现在 `**` 与 `<<` 溢出时改走十进制串求幂/乘法，结果仍是精确值。


    a: big = 2 ** 127
    print(a)
    b: big = 2 ** 200
    print(b)
    c: big = 10 ** 30
    print(c)
    d: big = 1 << 127
    print(d)
    e: big = 3 << 100
    print(e)
    f: big = 1 << 10
    print(f)

_case_1()
_case_2()
_case_3()
_case_4()

