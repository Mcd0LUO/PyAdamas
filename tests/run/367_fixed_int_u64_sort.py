# 367_fixed_int_u64_sort —— P1 收尾：u64 列表的无符号排序。
# sort()/sorted()/min/max 对 u64 元素按无符号比较（≥2^63 的位模式在 int64
# 视角是负数，此前 sort 按有符号比会排错；min/max 走 IR Cmp 早已正确）。
# 比较器按元素类型分派：sort_kind 新增 5=u64，容器描述符新增 'u'；
# 其它类型（int/窄定宽/float/str/tuple）的排序路径逐字不变。
# sorted(key=)：标注 -> u64 的键函数与恒等 lambda（lambda x: x）按无符号；
# 非恒等无标注键函数键域未知，退机器字比较（既有限制，见 landing §6）。
# 本用例与 CPython 逐字节对拍（future annotations + cast_u64  wrap 桩）。

l: list[u64] = [18446744073709551615, 1, 9223372036854775808, 5, 9223372036854775807, 0]
l.sort()
print(l)
print(sorted(l, reverse=True))
print(min(l), max(l))
m: list[u64] = [18446744073709551615, 9223372036854775808, 2, 18446744073709551614]
print(sorted(m))
print(sorted(m, key=lambda x: x))
# 稳定性：相等键保持原序（tuple 元素用 cast 构造，u64 键）
pairs: list[tuple[u64, int]] = [(cast_u64(-1), 1), (cast_u64(-9223372036854775807 - 1), 2), (cast_u64(-1), 3), (cast_u64(1), 4)]
print(sorted(pairs))
def first(p: tuple[u64, int]) -> u64:
    return p[0]
print(sorted(pairs, key=first))
# 嵌套容器里的 u64（内层用标注声明）
a: list[u64] = [18446744073709551615]
b: list[u64] = [9223372036854775808]
c: list[u64] = [1]
nl: list[list[u64]] = [a, b, c]
print(sorted(nl))
# 其它类型不受影响
i: list[int] = [3, -1, 2]
i.sort()
print(i)
u8: list[u8] = [255, 1, 128]
u8.sort()
print(u8)
i8: list[i8] = [-128, 127, 0]
i8.sort()
print(i8)
f: list[float] = [2.5, -1.0, 0.0]
f.sort()
print(f)
s: list[str] = ["b", "a", "c"]
s.sort()
print(s)
t: list[tuple[int, str]] = [(2, "b"), (1, "a"), (2, "a")]
print(sorted(t))
# 大列表（触发 timsort 归并路径，>64 元素）
big: list[u64] = []
k: u64 = 0
while k < 200:
    big.append(18446744073709551615 - k * 7)
    k += 1
big.sort()
print(big[0], big[1], big[199], len(big))
print(sorted(big, reverse=True)[0])
