# 455: 正整数 2 的幂除数的 // 与 %（0.385 强度削减）。
# 以前：算商 → 算余数 → 按余数符号修正，约 16 条指令 + 一个数据相关分支；
# 现在：// 是一条 sarq，% 是一条 andq。三条式子（含 INT64_MIN、负数）
# 都要与 CPython 逐位一致。

MINV = -9223372036854775807 - 1
xs: list[int] = [0, 1, -1, 2, -2, 7, -7, 15, -15, 16, -16, 1023, -1023,
                 9223372036854775807, MINV, -9223372036854775807]
ds: list[int] = [2, 4, 8, 1024]

for x in xs:
    for d in ds:
        print(x, d, x // d, x % d)

# 除数为负：走的是另一条路径（floor/ceil 换算），一并钉住
for x in [7, -7, 0, MINV]:
    for d in [-2, -8]:
        print(x, d, x // d, x % d)

# 复合形态：三角数公式（光谱范数的内层）+ 混入负数
for n in [0, 1, 5, 600]:
    t = n * (n + 1) // 2
    print("tri", n, t)
for i in range(-3, 4):
    print("tri2", i, i * (i + 1) // 2)
